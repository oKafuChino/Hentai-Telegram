"""Interactive installer configuration. Never source dotenv as shell code."""
import getpass
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV = ROOT / ".env"


def parse(text):
    result = {}
    for line in text.splitlines():
        if not line or line.lstrip().startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == "'":
            value = value[1:-1].replace("\\'", "'").replace("\\\\", "\\")
        elif len(value) >= 2 and value[0] == value[-1] == '"':
            raise ValueError("安装脚本仅支持未加引号或单引号 .env 值，请转换后重试")
        result[key.strip()] = value
    return result


def encode(value):
    if any(c in value for c in "\r\n\x00"):
        raise ValueError("配置不能包含换行或 NUL")
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def save(values):
    if any(not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key) for key in values):
        raise ValueError("配置键名无效")
    text = "# Generated by scripts/configure.py; contains credentials.\n"
    text += "".join(f"{key}={encode(value)}\n" for key, value in values.items())
    fd, filename = tempfile.mkstemp(prefix=".env.", suffix=".tmp", dir=ROOT)
    temporary = Path(filename)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(ENV)
    finally:
        temporary.unlink(missing_ok=True)


def ask(label, default="", secret=False):
    prompt = label + (f"（默认: {default}）" if default else "") + ": "
    value = getpass.getpass(prompt) if secret else input(prompt).strip()
    value = value or default
    if not value:
        raise ValueError(f"{label}不能为空")
    encode(value)
    return value


def main():
    action = sys.argv[1] if len(sys.argv) > 1 else "initial"
    values = parse((ENV if ENV.exists() else ROOT / ".env.example").read_text(encoding="utf-8"))
    if action == "ids":
        uid, gid = values.get("APP_UID", "1000"), values.get("APP_GID", "1000")
        if not uid.isdigit() or not gid.isdigit() or int(uid) <= 0 or int(gid) <= 0:
            raise ValueError("UID/GID 必须为非 root 正整数")
        print(uid, gid)
        return
    if action == "initial":
        if ENV.exists():
            print("检测到现有 .env，保留 Token 及其他已有配置。")
            return
        values["TELEGRAM_BOT_TOKEN"] = ask("Telegram Bot Token", secret=True)
        values["TELEGRAM_ALLOWED_USER_IDS"] = ask("管理员 Telegram 数字用户 ID（逗号分隔）")
        if not re.fullmatch(r"[1-9][0-9]*(,[1-9][0-9]*)*", values["TELEGRAM_ALLOWED_USER_IDS"]):
            raise ValueError("用户 ID 格式无效，必须为纯数字")
        values["TELEGRAM_CHANNEL_ID"] = ask("发布目标 Telegram 频道 ID 或 @用户名（例如 -1001234567890）")
        values["TELEGRAPH_AUTHOR_NAME"] = ask("Telegraph 文章作者名", "Hentai-Telegram")

        use_s3 = ask("是否配置 Cloudflare R2 / Backblaze B2 等 S3 兼容对象存储？(y/n)", "y").lower() in {"y", "yes"}
        if use_s3:
            values["S3_ENDPOINT_URL"] = ask("S3 / R2 / B2 Endpoint 地址（例如 https://<account_id>.r2.cloudflarestorage.com）")
            values["S3_BUCKET_NAME"] = ask("存储桶名称 (Bucket Name)")
            values["S3_ACCESS_KEY_ID"] = ask("Access Key ID (KeyID)", secret=True)
            values["S3_SECRET_ACCESS_KEY"] = ask("Secret Access Key (ApplicationKey)", secret=True)
            values["S3_PUBLIC_URL"] = ask("图片公开访问域名（例如 https://img.example.com 或 https://pub-xxx.r2.dev）")
            values["S3_REGION_NAME"] = ask("S3 Region 区域（R2 填 auto，B2 填对应地区如 us-west-004）", "auto")
    else:
        raise ValueError(f"Unknown action: {action}")
    save(values)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, EOFError, KeyboardInterrupt) as exc:
        raise SystemExit(str(exc) or "已取消；未继续部署")
